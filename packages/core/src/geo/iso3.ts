/**
 * How the model marks a dimension, from its member's `meta`: true, a country
 * code; false, not one; undefined, unmarked (decided by its values).
 */
export function countryCodeMarkingOf(meta: unknown): boolean | undefined {
  const wechart = (meta as { wechart?: unknown } | null | undefined)?.wechart;
  const marking = (wechart as { countryCode?: unknown } | null | undefined)?.countryCode;
  return typeof marking === 'boolean' ? marking : undefined;
}

/**
 * Whether a dimension holds ISO-3 country codes (AC-313): as the model marks
 * it, else when every non-empty value is one, and there is at least one.
 */
export function holdsCountryCodes(
  values: readonly unknown[],
  marking: boolean | undefined,
): boolean {
  if (marking !== undefined) return marking;
  const present = values.filter((value) => value !== null && value !== undefined && value !== '');
  return (
    present.length > 0 &&
    present.every((value) => typeof value === 'string' && ISO_3166_ALPHA_3.has(value))
  );
}
